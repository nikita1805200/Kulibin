const SYSTEM_PROMPT = `Ты — ведущий эксперт-методист ФИПИ и преподаватель высшей категории платформы «Кулибин».
Твоя задача — составлять авторские, уникальные учебные задания (включая стандарты ОГЭ и ЕГЭ), строго соответствующие школьной программе РФ и спецификациям ФИПИ.

Правила:
1. Задание должно быть методически корректным, с однозначным, проверяемым числовым или кратким ответом.
2. Все расчеты должны быть точными и перепроверенными тобой шаг за шагом.
3. Обязательно давай развернутое пошаговое решение (solution) и четкий критерий оценивания (criteria).
4. Ответ ВСЕГДА возвращай строго в формате JSON без лишних пояснений вне структуры.`;

/**
 * Формирование Few-Shot промпта с эталонами ФИПИ
 */
function buildTaskPrompt({ subjectName, grade, topic, examType, fewShotExamples = [] }) {
  const examLabel = examType === 'oge' ? 'ОГЭ (9 класс)' : examType === 'ege' ? 'ЕГЭ (10-11 класс)' : `Школьная программа (${grade} класс)`;

  let examplesText = '';
  if (fewShotExamples.length > 0) {
    examplesText = '\n\nЭТАЛОННЫЕ ПРИМЕРЫ ЗАДАНИЙ ФИПИ ДЛЯ ОРИЕНТИРА:\n' +
      fewShotExamples.map((ex, i) => 
        `Пример ${i + 1}:\n` +
        `- Тема: ${ex.topic}\n` +
        `- Условие: ${ex.condition}\n` +
        `- Решение: ${ex.solution}\n` +
        `- Ответ: ${ex.answer}\n` +
        `- Критерий: ${ex.criteria || '1 балл'}`
      ).join('\n\n') + '\n\n';
  }

  const userContent = `Составь НОВОЕ авторское задание по следующим параметрам:
- Предмет: ${subjectName}
- Класс: ${grade}
- Направление: ${examLabel}
- Тема: ${topic}
${examplesText}
Требования к ответу:
Сгенерируй JSON со следующими обязательными полями:
{
  "title": "Краткое название задачи (например: ОГЭ №9. ${topic})",
  "examType": "${examType ? examType.toUpperCase() : 'ТРЕНАЖЕР'}",
  "grade": ${grade},
  "question": "Четкий и понятный текст условия задачи с числовыми данными",
  "hints": ["Краткая подсказка по первому шагу"],
  "solution": "Пошаговое, последовательное решение с вычислениями",
  "answer": "Финальный точный ответ",
  "criteria": "Критерий оценивания в баллах ФИПИ",
  "difficulty": "базовый"
}`;

  return [
    { role: 'system', content: SYSTEM_PROMPT },
    { role: 'user', content: userContent }
  ];
}

module.exports = {
  SYSTEM_PROMPT,
  buildTaskPrompt
};
